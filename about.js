/* ── Language engine ── */
let currentLang = 'cn';

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === 'cn' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[key]) el.innerHTML = i18n[key][lang];
  });
  document.getElementById('btn-cn').classList.toggle('active', lang === 'cn');
  document.getElementById('btn-en').classList.toggle('active', lang === 'en');
}

/* ── Nav (always solid on inner pages) ── */
const nav = document.getElementById('nav');
window.addEventListener('scroll', () => {
  nav.classList.toggle('solid', window.scrollY > 40);
}, { passive: true });

/* ── Mobile menu ── */
function toggleMenu() {
  document.getElementById('mobileMenu').classList.toggle('open');
}

/* ── Nav active style ── */
const style = document.createElement('style');
style.textContent = `
  nav.solid .nav-active { color: var(--red) !important; }
  nav.solid .nav-active::after { width: 100% !important; }
`;
document.head.appendChild(style);

/* ── Scroll reveal ── */
const io = new IntersectionObserver(entries => {
  entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('in'); });
}, { threshold: 0.1, rootMargin: '0px 0px -48px 0px' });
document.querySelectorAll('.rv').forEach(el => io.observe(el));

/* ── Init ── */
setLang('cn');
